"""Build the set table embedded in one_click_armor_set.lua (between the SET TABLE markers).

Inputs:
  _research/equip_set/armor_sets.json      the kit table dumped by FileDiver's armor-set-json-dumper (NOTES.md 1)
  _research/equip_set/offers_25480438.log  the offers table dumped by recon 1 (NOTES.md 3): order, type, price
  _research/equip_set/wiki_sets.json       the wiki's sets (research/fetch_wiki.py)
  _research/equip_set/strings/             the game's string tables (English: unnamed kits' and player cards' names)
  _research/game_25480438.dll              the game.dll dump (its player card table)

Rules (NOTES.md sections 1, 3, 7, 20 and 23):
  0. The wiki (research/wiki_rule.py): every warbond page, Superstore page and special source's armor, helmet, cape
     and player card, matched by name. Shared pieces (the starter cape and card on every B-01 Tactical copy) belong
     to several sets. MANUAL adds pieces by hand.
  Rules 1-4 only take items no wiki name matched:
  1. Developer names: armor_/helmet_/cape_/banner_warbond_<group>_<n> form one set. Player cards (banner_*) aren't in
     the kit table, so their ids are the thin hashes of the names the kits imply.
  2. Other kits: a helmet and a body sharing a dlc_id form a set, plus a cape linked to that body through a dlc_id or
     a bundle set_id (not the catch-all sets 0 and 934502665).
  3. Superstore: each release block of the offers table carries one Super Credits armor with its cape and card, and
     the prices come in tiers (armor 250 -> cape 100, card 35; 300 -> 120, 40; 400 -> 250, 75). A Super Credits cape
     or card without a set joins the Super Credits armor of its tier within NEAR offers, when that pairing is the
     only one possible on both sides.
  4. Free sets: a free armor with no cape or card, and exactly one cape and one card without a set right beside it
     (ADJACENT offers), with no other armor that near them.
Only sets with at least two different slots are kept. Set labels are the armor's English name (a number is added
when two sets share it).

Also generated: every kit's slot and weight class (KIT_SLOT, for Randomize Armor): an armor's class is its torso armor
piece's weight (the armory's Light/Medium/Heavy label; agrees with HD2Runtime for all 135 armors), a helmet's the
class of the armor of its set (else of the armor with its name).

Usage: python build_set_table.py
"""
import collections
import json
import re
import struct
import sys
from pathlib import Path

from crack_kit_names import thin
import wiki_rule

MOD = Path(__file__).resolve().parents[1]
SCRIPT = MOD / 'one_click_armor_set.lua'
RESEARCH = MOD.parents[1] / '_research' / 'equip_set'
KITS = RESEARCH / 'armor_sets.json'
OFFERS = RESEARCH / 'offers_25480438.log'
WIKI = RESEARCH / 'wiki_sets.json'
DUMP = MOD.parents[1] / '_research' / 'game_25480438.dll'
# Pieces added by hand: armor name -> [(slot, name)]. DP-00 Tactical (Liberty Day) has its own cape on the wiki and no
# card: the starter card, as the user asked (2026-10-12).
MANUAL = {'DP-00 Tactical': [('p', 'Solid Black')]}
# Name keys (name_upper) per kit, from HD2-Transmog's catalog of the same game build.
NAME_KEYS = MOD.parents[1] / '_examples' / 'HD2-Transmog' / 'reference' / 'current_catalog.json'
BEGIN, END = '-- BEGIN SET TABLE (generated by research/build_set_table.py)\n', '-- END SET TABLE\n'
SLOT = {'Helmet': 'h', 'Armor': 'b', 'Cape': 'c'}
SLOT_WORD = {'h': 'helmet', 'b': 'armor', 'c': 'cape', 'p': 'card'}
CATCH_ALL_SETS = {0, 934502665}
SUPER_CREDITS = 0xcf875032
TIERS = {250: (100, 35), 300: (120, 40), 400: (250, 75)}  # armor price -> (cape price, card price)
NEAR, ADJACENT = 16, 3
CARD_TYPE = 9


def kit_id(k):
    return int(k['id'], 16) if k['id'].startswith('0x') else thin(k['id'])


def load_offers(path):
    """Offers in table order: (index, item, type, currency, price)."""
    rows = []
    for line in open(path, encoding='utf-8'):
        if line.startswith('#'):
            continue
        i, e, _, s = line.split()
        e, s = bytes.fromhex(e), bytes.fromhex(s)
        rows.append((int(i), struct.unpack_from('<I', e, 8)[0], struct.unpack_from('<I', s, 12)[0],
                     struct.unpack_from('<I', s, 28)[0], struct.unpack_from('<I', s, 32)[0]))
    return rows


def base_sets(kits):
    sets = collections.defaultdict(dict)  # key -> {item id: slot}
    assigned = set()
    for k in kits:
        m = re.fullmatch(r'(armor|helmet|cape)_warbond_(.+)_(\d+)', k['id'])
        if m:
            key = 'w%s_%s' % (m.group(2), m.group(3))
            sets[key][kit_id(k)] = SLOT[k['kit_type']]
            assigned.add(kit_id(k))
    for key in list(sets):
        card = thin('banner_warbond_' + key[1:])
        sets[key][card] = 'p'
    by_dlc = collections.defaultdict(list)
    for k in kits:
        if kit_id(k) not in assigned and k['dlc_id'] != 0:
            by_dlc[k['dlc_id']].append(k)
    by_set = collections.defaultdict(list)
    for dlc, group in by_dlc.items():
        by_set[group[0]['set_id']].append(dlc)
    for dlc, group in by_dlc.items():
        slots = {SLOT[k['kit_type']] for k in group}
        if 'b' not in slots and 'h' not in slots:
            continue
        key = 'd%d' % dlc
        for k in group:
            sets[key][kit_id(k)] = SLOT[k['kit_type']]
    # Capes alone in their dlc, linked to exactly one body group through a bundle set_id.
    for dlc, group in by_dlc.items():
        if {SLOT[k['kit_type']] for k in group} != {'c'} or group[0]['set_id'] in CATCH_ALL_SETS:
            continue
        partners = [d for d in by_set[group[0]['set_id']] if d != dlc and 'd%d' % d in sets]
        if len(partners) == 1:
            for k in group:
                sets['d%d' % partners[0]][kit_id(k)] = 'c'
    return sets


def offer_rules(sets, slot_of, offers):
    """Rules 3 and 4: link capes and cards without a set to a neighboring armor of the same kind of release."""
    member = {item: key for key, m in sets.items() for item in m}
    first = {}  # item -> its first offer row
    for r in offers:
        first.setdefault(r[1], r)
    rows = sorted(first.values())

    def slot(r):
        return 'p' if r[2] == CARD_TYPE else slot_of.get(r[1])

    armors = collections.defaultdict(list)  # set key -> offer rows of its body and helmet (non-warbond sets)
    for r in rows:
        key = member.get(r[1])
        if key and key[0] == 'd' and slot(r) in ('b', 'h'):
            armors[key].append(r)
    orphans = [r for r in rows if slot(r) in ('c', 'p') and r[1] not in member]

    def has(key, s):
        return any(v == s for v in sets[key].values())

    def distance(r, key):
        return min(abs(r[0] - a[0]) for a in armors[key])

    links = []
    # Rule 3: Super Credits tiers.
    sc = {}
    for key, rs in armors.items():
        body = [r for r in rs if slot(r) == 'b' and r[3] == SUPER_CREDITS and r[4] in TIERS]
        if body:
            sc[key] = TIERS[body[0][4]]
    for s, t in (('c', 0), ('p', 1)):
        cand = collections.defaultdict(list)  # orphan -> armors it could join
        for r in orphans:
            if slot(r) == s and r[3] == SUPER_CREDITS:
                for key, prices in sc.items():
                    if prices[t] == r[4] and not has(key, s) and distance(r, key) <= NEAR:
                        cand[r].append(key)
        claims = collections.Counter(k for ks in cand.values() for k in ks)
        for r, ks in cand.items():
            if len(ks) == 1 and claims[ks[0]] == 1:
                links.append((r[1], ks[0], s, 'Superstore price tier'))
    # Rule 4: a free armor with exactly one cape and one card right beside it, and no other armor near them.
    free = [key for key, rs in armors.items() if all(r[3] != SUPER_CREDITS for r in rs)
            and not has(key, 'c') and not has(key, 'p')]
    for key in free:
        near = [r for r in orphans if r[3] != SUPER_CREDITS and distance(r, key) <= ADJACENT]
        if sorted(slot(r) for r in near) != ['c', 'p']:
            continue
        if any(other != key and distance(r, other) <= ADJACENT for r in near for other in armors):
            continue
        for r in near:
            links.append((r[1], key, slot(r), 'beside its armor'))
    for item, key, s, how in links:
        sets[key][item] = s
    return links


def english_labels(sets, names):
    """Set key -> label: the armor's English name (else the helmet's, else the cape's), numbered when two sets share
    it."""
    raw = {}
    for key, members in sets.items():
        name = None
        for s in ('b', 'h', 'c', 'p'):
            named = sorted(i for i, v in members.items() if v == s and i in names
                           and not re.fullmatch(r'[0-9a-f]{5,8}', names[i]))
            if named:
                name = names[named[0]]
                break
        # Prefer a mixed-case spelling of the same name (some armors are named in capitals, their helmets not).
        spellings = [names[i] for i in sorted(members) if i in names]
        name = next((n for n in spellings if name and n.lower() == name.lower() and n != n.upper()), name)
        raw[key] = name or 'Unnamed %s' % key
    count = collections.Counter(raw.values())
    seen = collections.Counter()
    labels = {}
    for key in sorted(sets, key=lambda k: (raw[k], min(sets[k]))):
        n = raw[key]
        seen[n] += 1
        labels[key] = n if count[n] == 1 else '%s (%d)' % (n, seen[n])
    return labels


def armor_classes(kits, sets, names):
    """Item -> weight class ('l', 'm', 'h'): an armor's torso armor piece weight (stocky body, else any), a helmet's
    the class of its set's armor, else of the armor with its name."""
    w = {'light': 'l', 'medium': 'm', 'heavy': 'h'}
    cls = {}
    for k in kits:
        if k['kit_type'] != 'Armor':
            continue
        for body in ('stocky', 'any'):
            ws = {p['weight'] for bt in k['body_types'] if bt['body_type'] == body for p in bt['pieces']
                  if p['slot'] == 'torso' and p['piece_type'] == 'armor'}
            if len(ws) == 1:
                cls[kit_id(k)] = w[ws.pop()]
                break
    by_name = collections.defaultdict(set)
    for i, c in cls.items():
        by_name[wiki_rule.norm(names[i])].add(c)
    for members in sets.values():
        armor = {cls[i] for i, s in members.items() if s == 'b' and i in cls}
        for i, s in members.items():
            if s == 'h' and len(armor) == 1:
                cls.setdefault(i, next(iter(armor)))
    for k in kits:
        i = kit_id(k)
        if k['kit_type'] == 'Helmet' and i not in cls and len(by_name[wiki_rule.norm(names[i])]) == 1:
            cls[i] = next(iter(by_name[wiki_rule.norm(names[i])]))
    return cls


def build():
    kits = json.load(open(KITS, encoding='utf-8'))
    by_id = {kit_id(k): k for k in kits}
    slot_of = {i: SLOT[k['kit_type']] for i, k in by_id.items()}
    offers = load_offers(OFFERS)
    ownable = {r[1] for r in offers}
    english = wiki_rule.english_strings(RESEARCH / 'strings')
    name_keys = json.load(open(NAME_KEYS, encoding='utf-8'))['kits']
    names = wiki_rule.kit_names(kits, kit_id, name_keys, english)
    cards = wiki_rule.card_names(DUMP.read_bytes(), english)
    index = wiki_rule.Index({s: {i: n for i, n in names.items() if slot_of[i] == s} for s in 'hbc'} | {'p': cards})
    groups = json.load(open(WIKI, encoding='utf-8'))['groups']
    wiki, report, named = wiki_rule.wiki_sets(groups, index, {kit_id(k): k['dlc_id'] for k in kits}, ownable, MANUAL)
    # Rules 1-4, for the items no wiki name matched.
    old = base_sets(kits)
    links = offer_rules(old, slot_of, offers)
    fallback = {}
    wiki_of = {i: key for key, m in wiki.items() for i in m}
    for key, m in old.items():
        rest = {i: s for i, s in m.items() if i not in named}
        if not rest:
            continue
        homes = collections.Counter(wiki_of[i] for i in m if i in wiki_of and m[i] in ('b', 'h'))
        if homes:  # unnamed copies (no name in the game's strings) follow their old partners into the wiki's set
            home = homes.most_common(1)[0][0]
            for i, s in rest.items():
                wiki[home].setdefault(i, s)
            report.append('%s: %d unnamed items follow their old set (%s)' % (home, len(rest), key))
        elif len(set(rest.values())) >= 2:
            fallback['rule:' + key] = rest
    links = [l for l in links if l[0] not in named]
    sets = {'wiki:' + k: m for k, m in wiki.items()} | fallback
    sets = {key: m for key, m in sets.items() if len(set(m.values())) >= 2}
    all_names = names | cards
    labels = english_labels(sets, all_names)
    members = {labels[key]: m for key, m in sets.items()}  # label -> {item: slot}
    set_label_names = set_names(members, all_names, name_keys)
    return members, set_label_names, all_names, links, report, armor_classes(kits, sets, names), by_id


def set_names(members, names, name_keys):
    """Per set: the armor's localization key (else the helmet's) and its English name as a fallback."""
    out = {}
    for label, ms in members.items():
        for s in ('b', 'h'):
            named = sorted(i for i, v in ms.items() if v == s and i in names
                           and not re.fullmatch(r'[0-9a-f]{5,8}', names[i]))
            if named:
                out[label] = (name_keys.get(str(named[0]), {}).get('name_upper', 0), names[named[0]].upper())
                break
    return out


def lua_string(s):
    return "'%s'" % s.replace('\\', '\\\\').replace("'", "\\'")


def kit_slots_block(by_id, classes):
    """Every kit's slot and weight class (Randomize Armor): item ids in hex, one string per slot and class (hx: a
    helmet with no known class). Player cards aren't kits: the script finds them by their offer type."""
    lines = ['-- Every helmet (h), armor (b) and cape (c) kit by slot and weight class (l, m, h; x unknown): item ids\n',
             '-- in hex (the script turns KIT_SLOT into item id -> slot, and KIT_SLOT.class into item id -> class)\n',
             'local KIT_SLOT = {\n']
    groups = collections.defaultdict(list)
    for i, k in by_id.items():
        s = SLOT[k['kit_type']]
        groups[s if s == 'c' else s + classes.get(i, 'x')].append('%08x' % i)
    for key in sorted(groups, key=lambda g: ('hbc'.index(g[0]), g)):
        ids = sorted(groups[key])
        lines.append('    %s = table.concat({\n' % key)
        for n in range(0, len(ids), 12):
            lines.append("        '%s',\n" % ' '.join(ids[n:n + 12]))
        lines.append("    }, ' '),\n")
    lines.append('}\n')
    return lines


def lua_block(members, names, by_id, classes):
    """SETS: [item] = {set, slot}, or {'*', slot, {sets}} for a piece several sets share."""
    of = collections.defaultdict(list)
    for label, ms in members.items():
        for item, s in ms.items():
            of[item].append((label, s))
    lines = [BEGIN, '-- [item id] = {set, slot}: slot h helmet, b body, c cape, p player card; a piece several sets\n',
             "-- share: {'*', slot, {sets}}\n", 'local SETS = {\n']

    def order(item):
        label, s = sorted(of[item])[0]
        return (label, 'hbcp'.index(s), item)

    for item in sorted(of, key=order):
        entries = sorted(of[item])
        s = entries[0][1]
        if len(entries) == 1:
            lines.append('    [0x%08x] = {%s, %s},\n' % (item, lua_string(entries[0][0]), lua_string(s)))
        else:
            lines.append("    [0x%08x] = {'*', %s, {%s}},\n" % (item, lua_string(s),
                                                              ', '.join(lua_string(l) for l, _ in entries)))
    lines += ['}\n', '-- [set] = {localization key of its armor name, English name}\n', 'local SET_NAMES = {\n']
    for label in sorted(names):
        loc, en = names[label]
        lines.append('    [%s] = {0x%08x, %s},\n' % (lua_string(label), loc, lua_string(en)))
    lines += ['}\n'] + kit_slots_block(by_id, classes) + [END]
    return ''.join(lines)


def main():
    members, set_label_names, names, links, report, classes, by_id = build()
    text = SCRIPT.read_text(encoding='utf-8')
    a, b = text.index(BEGIN), text.index(END) + len(END)
    SCRIPT.write_bytes((text[:a] + lua_block(members, set_label_names, by_id, classes) + text[b:]).encode('utf-8'))
    for line in report:
        print('wiki:', line)
    for item, key, s, how in links:
        print('fallback: linked %s %08x %-34s -> %s (%s)' % (SLOT_WORD[s], item, names.get(item, ''), key, how))
    slots = collections.Counter(''.join(sorted(set(m.values()), key='hbcp'.index)) for m in members.values())
    items = {i for m in members.values() for i in m}
    shared = sum(1 for i in items if sum(i in m for m in members.values()) > 1)
    print('%d sets, %d items (%d shared): %s' % (len(members), len(items), shared, dict(slots)))
    print('%d set names, %d without a localization key' % (len(set_label_names),
                                                            sum(1 for v in set_label_names.values() if not v[0])))
    print('%d kits by slot and class: %s' % (len(by_id), dict(collections.Counter(
        SLOT[k['kit_type']] + ('' if SLOT[k['kit_type']] == 'c' else classes.get(i, 'x')) for i, k in by_id.items()))))


if __name__ == '__main__':
    sys.exit(main())
